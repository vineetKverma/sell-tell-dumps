CREATE TABLE `prj-hds-np-data.voice_notes_poc.agent_events`
(
  timestamp TIMESTAMP NOT NULL OPTIONS(description="Time of the event."),
  event_id STRING OPTIONS(description="Unique event identifier generated by ADK."),
  event_type STRING OPTIONS(description="Type of the event, e.g. INVOCATION_STARTING, MODEL_CALL_STARTING."),
  agent STRING OPTIONS(description="Agent name emitting the event."),
  session_id STRING OPTIONS(description="ADK session identifier."),
  invocation_id STRING OPTIONS(description="ADK invocation identifier."),
  user_id STRING OPTIONS(description="User identifier."),
  trace_id STRING OPTIONS(description="OpenTelemetry / Cloud Trace trace ID."),
  span_id STRING OPTIONS(description="OpenTelemetry span ID."),
  parent_span_id STRING OPTIONS(description="Parent OpenTelemetry span ID."),
  content JSON OPTIONS(description="Event payload / content as JSON."),
  content_parts ARRAY<STRUCT<
    mime_type STRING,
    uri STRING,
    object_ref STRUCT<
      uri STRING,
      version STRING,
      authorizer STRING,
      details JSON
    >,
    text STRING,
    part_index INT64,
    part_attributes STRING,
    storage_mode STRING
  >> OPTIONS(description="Structured parts of the event content."),
  attributes JSON OPTIONS(description="Arbitrary event attributes / metadata."),
  latency_ms JSON OPTIONS(description="Latency metrics for model calls and executions."),
  status STRING OPTIONS(description="Event status, e.g. SUCCESS, ERROR."),
  error_message STRING OPTIONS(description="Error message if event status is ERROR."),
  is_truncated BOOL OPTIONS(description="True if content was truncated to fit payload limits.")
)
PARTITION BY DATE(timestamp)
CLUSTER BY event_type, agent, user_id
OPTIONS(
  description="ADK BigQuery Agent Analytics Plugin raw event log (AIML-2823).",
  labels=[("adk_schema_version", "2")]
);
